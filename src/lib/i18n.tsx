export function translate(key: string, langCode: string): string {
  const normalizedLang = langCode || 'en';
  const dict = TRANSLATIONS[normalizedLang] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}

interface LanguageContextType {
  langCode: string;
  langName: string;
  refreshKey: number;
  setLanguage: (code: string, name: string) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  langCode: 'en',
  langName: 'English',
  refreshKey: 0,
  setLanguage: () => {},
  t: (key: string) => key,
});

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [langCode, setLangCode] = useState<string>(() => {
    return localStorage.getItem('selected_language_code') || 'en';
  });
  const [langName, setLangName] = useState<string>(() => {
    return localStorage.getItem('selected_language_name') || 'English';
  });
  const [refreshKey, setRefreshKey] = useState<number>(0);

  const setLanguage = (code: string, name: string) => {
    setLangCode(code);
    setLangName(name);
    setRefreshKey((prev) => prev + 1);

    localStorage.setItem('selected_language_code', code);
    localStorage.setItem('selected_language_name', name);

    // Dispatch global event
    window.dispatchEvent(new CustomEvent('appLanguageChanged', { detail: { code, name } }));
  };


  // Listen for storage or custom events across frames
  useEffect(() => {
    const handleAppLanguageChanged = (e: Event) => {
      const customEvent = e as CustomEvent<{ code: string; name: string }>;
      if (customEvent.detail && customEvent.detail.code) {
        setLangCode(customEvent.detail.code);
        setLangName(customEvent.detail.name || customEvent.detail.code);
        setRefreshKey((prev) => prev + 1);
      }
    };

    window.addEventListener('appLanguageChanged', handleAppLanguageChanged);
    window.addEventListener('storage', (e) => {
      if (e.key === 'selected_language_code' && e.newValue) {
        setLangCode(e.newValue);
        setLangName(localStorage.getItem('selected_language_name') || e.newValue);
        setRefreshKey((prev) => prev + 1);
      }
    });

    return () => {
      window.removeEventListener('appLanguageChanged', handleAppLanguageChanged);
    };
  }, []);

  const t = (key: string) => translate(key, langCode);

  return (
    <LanguageContext.Provider value={{ langCode, langName, refreshKey, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);

export function getStoredLanguage(): { code: string; name: string } {
  const code = localStorage.getItem('selected_language_code') || 'en';
  const name = localStorage.getItem('selected_language_name') || 'English';
  return { code, name };
}

export function applyLanguage(langCode: string, langName: string) {
  localStorage.setItem('selected_language_code', langCode);
  localStorage.setItem('selected_language_name', langName);
}
